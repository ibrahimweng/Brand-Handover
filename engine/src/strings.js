const HAVE = { en: EN, fr: FR, he: HE, ja: JA };

// The language a document is written in, which is the engine's unless the
// project's own is one the engine can write — and it is asked per document,
// because the two are not written from the same words. Verdon shipped a French
// manual and a deck of English prose under lang="fr", which is the thirtieth
// round's fault repeated one level down: the check was that a language had been
// declared, not that the document was in it.
function resolve(project, which = 'manual') {
  const want = String((project && project.language) || 'en').toLowerCase().split(/[-_]/)[0];
  const asked = HAVE[want];
  const set = asked && (asked.writes || ['manual']).indexOf(which) > -1 ? asked : EN;
  // A key this dictionary does not have still gets written, in English, because
  // half a page in the right language beats none — but the page keeps a list of
  // what it had to fall back on, and the build reads it. A silent fallback is
  // how a document ends up declaring a language it is not written in.
  const missed = new Set();
  // A measurement dropped into a right-to-left sentence is reordered by the
  // browser, and what comes out is a different number. `#C8873A` is drawn
  // `C8873A#`; `18 59 58` is drawn `58 59 18`, which is a different colour;
  // `122 × 50 px` is drawn `px 50 × 122`, which is a different shape; `1385 C`
  // is drawn `C 1385`, which is a different Pantone to send to a press. The
  // file is right in every one of those and the reader is shown something else.
  //
  // A value is its own run and has to say so. U+2068 FIRST STRONG ISOLATE and
  // U+2069 POP DIRECTIONAL ISOLATE do exactly that and are characters rather
  // than markup, so they survive escaping and reach the page through every
  // caller — which matters, because these values are set by a hundred callers
  // and isolated in one place. First-strong rather than left-to-right, so a
  // value that is itself Hebrew is left alone.
  //
  // Only where the document runs right to left. In en and fr it would be bytes
  // that change nothing, and there is no reason for a language to pay for a
  // problem it does not have.
  // Isolate the run rather than the value. Isolating each value on its own
  // left the characters between two of them — the arithmetic in `140 ÷ 7 = 20`,
  // the separator in `3.0.0 · 67` — outside any isolate, and a neutral between
  // two isolated runs takes the paragraph's direction: the sum came out
  // `20 = 7 ÷ 140` and the footer `67 · 3.0.0`. A run of characters with no
  // Hebrew in it is one left-to-right thing however many values went into it.
  // U+0000 is the sentinel a document leaves where the brand's own name goes,
  // filled in with markup afterwards. It has to break a run, or the isolate
  // ends up around the brand name too and first-strong resolves the whole
  // thing right to left: the footer read `67 · 3.0.0` for `3.0.0 · 67`.
  const RUN = /[^֐-ࣿיִ-﷿ﹰ-﻿⁦-⁩\u0000]*[0-9A-Za-z][^֐-ࣿיִ-﷿ﹰ-﻿⁦-⁩\u0000]*/g;
  const isolate = (out) => out.replace(RUN, (run) => {
    // trailing sentence punctuation belongs to the sentence, not to the value:
    // an isolate around `WCAG 2.2.` puts the full stop at the run's left-hand
    // end, which in a right-to-left sentence is the middle of it
    // Punctuation at either edge belongs to the sentence, not to the value.
    // An isolate around `WCAG 2.2.` puts the full stop at the run's left-hand
    // end, which in a right-to-left sentence is the middle of it; one that
    // starts at `: 140 ÷ 7` takes the colon off the clause it belongs to.
    const core = run.replace(/^[\s.,;:!?]+/, '').replace(/[\s.,;:!?]+$/, '');
    if (!core) return run;
    const at = run.indexOf(core);
    return `${run.slice(0, at)}\u2068${core}\u2069${run.slice(at + core.length)}`;
  });
  const t = (key, vars) => {
    let s = set[key];
    if (s === undefined) { if (set !== EN && EN[key] !== undefined) missed.add(key); s = EN[key]; }
    if (s === undefined) return key;
    for (const [k, v] of Object.entries(vars || {})) s = s.split(`{${k}}`).join(String(v));
    return set.dir === 'rtl' ? isolate(s) : s;
  };
  // The same lookup, in the form that agrees with a noun. A language says
  // which of its nouns are feminine and puts the second form of a key under
  // the same name with an `f` on the end; anything that has neither is
  // answered by `t` unchanged, which is every key in English.
  const genderOf = (key) => (set.gender && set.gender[key]) || '';
  const agree = (key, nounKey, vars) => {
    const g = genderOf(nounKey);
    return t(g && set[key + g] !== undefined ? key + g : key, vars);
  };
  return { lang: set.lang, dir: set.dir, name: set.name, t, agree, document: which,
    // what this script asks of a line, where it asks anything
    wrap: set.wrap || null, measure: set.measure || 'ch',
    // The canvas runs half in the browser, so its words have to travel there.
    // Handed over as they are written, with their {slots} still in them: a
    // value is substituted the moment it is known and that is on the other
    // side. HandoverRender.t is the same lookup, and a test holds the two to
    // each other.
    words: () => {
      const out = { lang: set.lang, dir: set.dir };
      for (const k of Object.keys(set)) if (/^cv/.test(k)) out[k] = t(k);
      for (const k of CANVAS_SHARED) if (set[k] !== undefined || EN[k] !== undefined) out[k] = t(k);
      return out;
    },
    // For a value a document sets straight into markup rather than through a
    // key. `t` isolates what it substitutes; a caption built as
    // `${caption} · ${t(label)}` never passes the caption through it, and
    // `120 px · comfortable` came out `comfortable · px 120`.
    iso: (v) => (set.dir === 'rtl' ? isolate(String(v)) : String(v)),
    // what the project asked for, and whether this document could be written in
    // it: the deck of a French project is English until deck.js takes its words
    // from here, and saying so is the difference between a claim and a lie
    wanted: want, wantedName: (asked && asked.name) || want,
    writes: (asked && (asked.writes || ['manual'])) || [],
    // Whether the brand's own language is the one this document is written in.
    // Where it is not, the brand's words carry their own lang and dir and the
    // document carries the engine's, which is what makes both claims true.
    speaksBrand: set.lang === want,
    brandLang: want, brandDir: (project && project.direction) || 'ltr',
    available: Object.keys(HAVE),
    // every key this document asked for and this dictionary did not have
    missed: () => [...missed].sort() };
}

// How much of a document was never written in the language it claims.
//
// Every check the engine had asked whether a language had been declared, and
// none of them looked at the page. Verdon's manual carried lang="fr" over 2,255
// words of which 2,034 were the English build's, word for word: the chrome came
// from this dictionary and the body was literals in documents/blocks.js that no
// dictionary had ever seen. A key that falls back can be counted; a sentence
// that never asks for a key cannot, and the only thing that sees it is the
// finished page beside the English one.
//
// Count the prose words the two renders share, as a multiset, over the words
// that could have been translated at all — a number, a hex code, a folder name
// and the brand's own vocabulary are the same in every language and are not
// evidence of anything. Sharing is an upper bound: `construction` is spelled
// the same in both, so a well translated page scores a little above zero rather
// than at it. Erring that way is the safe direction for a claim.
const NOT_PROSE = /^[^\p{L}]*$/u;
// A word, in a language that has them.
//
// Japanese does not. It is written without spaces, so this splitter returned a
// whole page as one token: `residue` on a Japanese manual came back
// {words: 1, shared: 0}, which reads as a perfect score and is a sample of one.
// Every check that measures what a language actually writes was blind to it,
// and would have been blind to a Japanese page that was secretly English too,
// because that page would have scored 1 out of 1 the other way.
//
// The unit that works for both is the character where a script is written
// without spaces and the space-delimited run everywhere else. It is not a
// tokeniser and does not pretend to be one — 録音室 is one word and three
// tokens here. For a ratio of how much of one page is word for word another
// that does not matter: what matters is that the denominator is the length of
// the text rather than one, and that a Latin word inside Japanese prose still
// comes out as itself.
const SOLID = /[\u3040-\u30FF\u3400-\u4DBF\u4E00-\u9FFF\uF900-\uFAFF\uFF66-\uFF9F]/;
const SPLIT = /[\s,.;:!?()[\]{}"'\u2018\u2019\u201c\u201d\u00b7\u2014\u2013\/|\u3000\u3001\u3002\u30FB\uFF08\uFF09\u300C\u300D\u300E\u300F\uFF1A\uFF1B\uFF01\uFF1F]+/u;
const splitWords = (t) => {
  const out = [];
  for (const run of String(t).split(SPLIT)) {
    let buf = '';
    for (const ch of run) {
      if (SOLID.test(ch)) { if (buf) { out.push(buf); buf = ''; } out.push(ch); }
      else buf += ch;
    }
    if (buf) out.push(buf);
  }
  return out;
};
function proseWords(html, skip) {
  const text = String(html)
    .replace(/<(script|style|svg)\b[^>]*>[\s\S]*?<\/\1>/gi, ' ')
    .replace(/url\(data:[^)]*\)/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&[a-z]+;|&#\d+;/gi, ' ');
  const out = [];
  for (const w of splitWords(text)) {
    const k = w.toLowerCase();
    if (!k || NOT_PROSE.test(k) || /^#?[0-9a-f]{3,8}$/.test(k)) continue;
    if (skip && skip.has(k)) continue;
    out.push(k);
  }
  return out;
}

// The words that are the project's own and mean nothing about translation.
// Everything that reaches a page through own() is the brand's, printed the same
// in both builds by design — Verdon's positioning is French in the English deck
// too — so counting it as "shared" would mark a well translated page down for
// carrying the brand's own language, which is the one thing it is supposed to do.
function ownVocabulary(project) {
  const p = project || {};
  const type = (p.tokens || {}).type || {};
  const bits = [p.brand, p.version]
    .concat(Object.keys((p.tokens || {}).colour || {}))
    .concat(Object.values(type.families || {}).map((f) => f.family))
    .concat((type.scale || []).map((s) => s.sample))
    .concat(Object.values(p.content || {}).filter((v) => typeof v === 'string'))
    .concat(((p.content || {}).misuse || []).map((m) => m && m.why))
    .concat((p.partners || []).map((x) => x.name))
    .concat((p.rules && p.rules.lockups) || [])
    .concat(Object.keys(((p.system || {}).motion || {}).durations || {}));
  const set = new Set();
  for (const b of bits) {
    // the same splitter proseWords uses, or a hyphenated word is stored as two
    // and looked up as one
    for (const w of splitWords(String(b == null ? '' : b).toLowerCase())) if (w) set.add(w);
  }
  return set;
}

function residue(wanted, english, project) {
  const skip = ownVocabulary(project);
  const a = proseWords(wanted, skip), b = proseWords(english, skip);
  const have = new Map();
  for (const w of b) have.set(w, (have.get(w) || 0) + 1);
  let shared = 0;
  for (const w of a) { const n = have.get(w) || 0; if (n > 0) { shared++; have.set(w, n - 1); } }
  return { words: a.length, shared, share: a.length ? shared / a.length : 0 };
}

module.exports = { EN, FR, HAVE, resolve, residue, proseWords };
